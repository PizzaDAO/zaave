// Regenerates src/lib/zaaveAbi.ts from the Foundry artifact (when it exists).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const artifact = fileURLToPath(new URL("../../contracts/out/Zaave.sol/Zaave.json", import.meta.url));
const out = fileURLToPath(new URL("../src/lib/zaaveAbi.ts", import.meta.url));

if (!existsSync(artifact)) {
  console.log(`No artifact at ${artifact}; run \`forge build\` in contracts/ first. Keeping existing ABI.`);
  process.exit(0);
}
const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
writeFileSync(
  out,
  `// Generated by scripts/sync-abi.mjs from contracts/out/Zaave.sol/Zaave.json. Do not edit.\nexport const zaaveAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`Wrote ${out} (${abi.length} entries)`);
